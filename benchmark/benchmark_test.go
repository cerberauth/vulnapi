func command(ctx context.Context, env []string, dir string, name string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(ctx, commandTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, name, args...) //nolint:gosec
	cmd.Env = env
	cmd.Dir = dir
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return strings.TrimSpace(stdout.String()), nil
}

func shell(ctx context.Context, env []string, script string) (string, error) {
	return command(ctx, env, ".", "sh", "-c", script)
}

func vulnapiVersion(ctx context.Context, repoRoot string) string {
	if version := os.Getenv("VULNAPI_VERSION"); version != "" {
		return version
	}
	if version, err := command(ctx, os.Environ(), repoRoot, "git", "describe", "--tags", "--always", "--dirty"); err == nil {
		return version
	}
	return "dev"
}

func challengesDir(t *testing.T, ctx context.Context, manifests []*benchmark.Manifest, work string) string {
	if dir := os.Getenv("CHALLENGES_DIR"); dir != "" {
		abs, err := filepath.Abs(dir)
		if err != nil {
			t.Fatal(err)
		}
		return abs
	}
	i := slices.IndexFunc(manifests, func(m *benchmark.Manifest) bool { return filepath.Base(m.Dir) == "challenges" })
	if i == -1 {
		return work
	}
	dir := filepath.Join(work, "api-vulns-challenges")
	for _, args := range [][]string{
		{"clone", "--quiet", "--filter=blob:none", challengesRepository, dir},
		{"-C", dir, "checkout", "--quiet", manifests[i].Version},
	} {
		if _, err := command(ctx, os.Environ(), ".", "git", args...); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

var unsafeChars = regexp.MustCompile(`[^a-zA-Z0-9]+`)

func runScan(ctx context.Context, env []string, bin, work string, m *benchmark.Manifest, s benchmark.Scan) benchmark.ScanResult {
	fail := func(err error) benchmark.ScanResult {
		return benchmark.ScanResult{Target: m.Name, Scan: s.Name, Err: err, Unexpected: map[string]int{}}
	}
	for _, script := range s.Setup {
		if _, err := shell(ctx, env, script); err != nil {
			return fail(err)
		}
	}
	var token string
	if s.Token != "" {
		var err error
		if token, err = shell(ctx, env, s.Token); err != nil || token == "" {
			return fail(fmt.Errorf("token: %v", err))
		}
	}

	reportPath := filepath.Join(work, unsafeChars.ReplaceAllString(m.Name+"-"+s.Name, "-")+".json")
	args := make([]string, 0, len(s.Args)+8)
	for _, arg := range s.Args {
		args = append(args, os.Expand(arg, func(key string) string {
			if key == "TOKEN" {
				return token
			}
			return os.Getenv(key)
		}))
	}
	args = append(args, "--output", reportPath, "--output-format", "json", "--quiet", "--no-progress", "--sqa-opt-out")

	scanCtx, cancel := context.WithTimeout(ctx, scanTimeout)
	defer cancel()
	cmd := exec.CommandContext(scanCtx, bin, args...) //nolint:gosec
	cmd.Env = env
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	runErr := cmd.Run()

	data, err := os.ReadFile(reportPath)
	if err != nil {
		return fail(fmt.Errorf("no report (%v): %s", runErr, strings.TrimSpace(stderr.String())))
	}
	report, err := benchmark.ParseReport(data)
	if err != nil {
		return fail(err)
	}
	return benchmark.Compare(m.Name, s, report)
}

func selected(m *benchmark.Manifest) bool {
	targets := os.Getenv("BENCHMARK_TARGETS")
	if targets == "" {
		return true
	}
	return slices.ContainsFunc(strings.Split(targets, ","), func(target string) bool {
		return strings.EqualFold(strings.TrimSpace(target), filepath.Base(m.Dir))
	})
}

func TestBenchmark(t *testing.T) {
	ctx := context.Background()
	repoRoot, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	work := t.TempDir()

	manifests, err := benchmark.LoadManifests(".")
	if err != nil {
		t.Fatal(err)
	}
	manifests = slices.DeleteFunc(manifests, func(m *benchmark.Manifest) bool { return !selected(m) })

	bin := os.Getenv("VULNAPI_BIN")
	if bin == "" {
		bin = filepath.Join(work, "vulnapi")
		if _, err := command(ctx, os.Environ(), repoRoot, "go", "build", "-o", bin, "."); err != nil {
			t.Fatal(err)
		}
	}

	composeFile, err := filepath.Abs("compose.yaml")
	if err != nil {
		t.Fatal(err)
	}
	env := append(os.Environ(),
		"COMPOSE_FILE="+composeFile,
		"COMPOSE_PROJECT_NAME=vulnapi-benchmark",
		"CHALLENGES_DIR="+challengesDir(t, ctx, manifests, work),
	)
	if os.Getenv("BENCHMARK_COMPOSE") != "false" {
		if _, err := command(ctx, env, ".", "docker", "compose", "up", "--detach", "--build", "--quiet-pull"); err != nil {
			t.Fatal(err)
		}
		if os.Getenv("BENCHMARK_KEEP") != "true" {
			t.Cleanup(func() {
				_, _ = command(context.Background(), env, ".", "docker", "compose", "down", "--volumes")
			})
		}
	}

	run := benchmark.Run{VulnAPIVersion: vulnapiVersion(ctx, repoRoot), Date: time.Now(), Manifests: manifests}
	for _, m := range manifests {
		for _, s := range m.Scans {
			result := runScan(ctx, env, bin, work, m, s)
			run.Results = append(run.Results, result)
			if result.Err != nil {
				t.Errorf("%s / %s: %v", m.Name, s.Name, result.Err)
			}
			for _, issue := range result.Regressions() {
				t.Errorf("%s / %s: %s is not detected by %s", m.Name, s.Name, issue.Title, issue.Check)
			}
			for _, issue := range result.Issues {
				if issue.Status == benchmark.StatusNowDetected {
					t.Logf("%s / %s: %s is now detected, remove knownMiss from the manifest", m.Name, s.Name, issue.Issue.Title)
				}
			}
		}
	}

	summary := os.Getenv("BENCHMARK_SUMMARY")
	if summary == "" {
		summary = filepath.Join("results", "summary.md")
	}
	if err := os.MkdirAll(filepath.Dir(summary), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(summary, []byte(run.Markdown("en")), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("summary written to %s", summary)

	if os.Getenv("BENCHMARK_DOCS") == "true" {
		for lang, frontmatter := range docsFrontmatter {
			path := filepath.Join(repoRoot, "docs", lang, "benchmark.mdx")
			if err := os.WriteFile(path, []byte(frontmatter+run.Markdown(lang)), 0o600); err != nil {
				t.Fatal(err)
			}
		}
	}
}
